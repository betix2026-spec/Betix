export function isLocale(value: string | undefined | null): value is Locale {
    return SUPPORTED_LOCALES.includes(value as Locale);
}

export function getLocaleFromPath(pathname: string): Locale | null {
    const segment = pathname.split("/").filter(Boolean)[0];
    return isLocale(segment) ? segment : null;
}

export function stripLocaleFromPath(pathname: string): string {
    const locale = getLocaleFromPath(pathname);
    if (!locale) return pathname;
    const stripped = pathname.replace(`/${locale}`, "") || "/";
    return stripped.startsWith("/") ? stripped : `/${stripped}`;
}

export function withLocale(pathname: string, locale: Locale): string {
    const cleanPath = stripLocaleFromPath(pathname);
    return cleanPath === "/" ? `/${locale}` : `/${locale}${cleanPath}`;
}

export function t(locale: Locale | undefined | null, key: DictionaryKey): string {
    const activeLocale = locale && dictionaries[locale] ? locale : DEFAULT_LOCALE;
    return dictionaries[activeLocale][key] || dictionaries[DEFAULT_LOCALE][key];
}

export function copy(locale: Locale | undefined | null, source: string): string {
    const activeLocale = locale && dictionaries[locale] ? locale : DEFAULT_LOCALE;
    return literalTranslations[source]?.[activeLocale] || source;
}

/**
 * AI-generated prediction text (match_summary, analysis) is stored as either a
 * legacy plain string (French only, pre-localization) or { fr, en, es, de }.
 * This picks the right language, falling back to French, then whatever exists.
 */
export function localizeAnalysisText(value: unknown, locale: Locale | undefined | null): string {
    if (typeof value === "string") return value;
    if (value && typeof value === "object") {
        const obj = value as Partial<Record<Locale, string>>;
        const activeLocale = locale && dictionaries[locale] ? locale : DEFAULT_LOCALE;
        return obj[activeLocale] || obj.fr || Object.values(obj).find((v) => !!v) || "";
    }
    return "";
}

/**
 * Plan/feature text (name, description, label) is stored as a French base
 * column plus optional per-locale columns (name_en, name_es, name_de, ...).
 * This picks the right one, falling back to the French base if the
 * translation hasn't been filled in yet.
 */
export function pickLocalized(
    locale: Locale | undefined | null,
    base: string | null | undefined,
    translations: { en?: string | null; es?: string | null; de?: string | null },
): string {
    const activeLocale = locale && dictionaries[locale] ? locale : DEFAULT_LOCALE;
    if (activeLocale === "fr") return base || "";
    const translated = translations[activeLocale as "en" | "es" | "de"];
    return translated || base || "";
}
